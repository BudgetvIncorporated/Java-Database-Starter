const fixture: Snapshot = {
  genres: [{ genre_id: 7, genre_name: "Synthetic Puzzle" }],
  users: [{ user_id: 11, username: "Fixture Player", email: "fixture@example.test" }],
  games: [{ game_id: 17, genre_id: 7, title: "Fixture 100% Game",
    launch_url: "https://example.test/game", release_date: "2020-01-01" }],
  user_games: [{ user_id: 11, game_id: 17, rating: null, play_count: 2 }],
};

function fixtureDdl() {
  return readFileSync(join(findJavaProject(), "src/main/resources/schema.sql"), "utf8")
    .replace(/PRAGMA foreign_keys = ON;/, "")
    .replace(/INTEGER PRIMARY KEY/g, "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    .replace("instr(email, '@')", "strpos(email, '@')")
    .replace(/date\(release_date\)/g, "to_char(release_date::date, 'YYYY-MM-DD')");
}

async function withDisposableStore(run: (pool: pg.Pool, store: PostgresLibraryStore) => Promise<void>) {
  const admin = new pg.Pool({ connectionString: process.env.DATABASE_URL });
  const schema = `library_concurrency_${Date.now()}_${process.pid}`;
  const pool = new pg.Pool({
    connectionString: process.env.DATABASE_URL,
    options: `-c search_path=${schema} -c statement_timeout=5000 -c lock_timeout=2000`,
    max: 2,
    connectionTimeoutMillis: 5000,
  });
  try {
    await admin.query(`CREATE SCHEMA ${schema}`);
    await pool.query(fixtureDdl());
    const store = new PostgresLibraryStore(pool);
    await store.importSnapshot(fixture);
    await run(pool, store);
  } finally {
    await pool.end();
    try { await admin.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`); }
    finally { await admin.end(); }
  }
}

// Delegate every query to PostgreSQL. Intercept only the boundary AFTER a
// selected table has really been read, so coordination needs no sleeps or mocks
// of PostgreSQL's transaction/snapshot behavior.
function observeExport(pool: pg.Pool, afterQuery: (sql: string) => Promise<void>) {
  const statements: string[] = [];
  let releases = 0;
  const observed: LibraryPool = {
    query: (sql, values) => pool.query(sql, values),
    connect: async () => {
      const client = await pool.connect();
      return {
        query: async (sql, values) => {
          statements.push(sql);
          const result = await client.query(sql, values);
          await afterQuery(sql);
          return result;
        },
        release: () => { releases++; client.release(); },
      };
    },
  };
  return { store: new PostgresLibraryStore(observed), statements, releases: () => releases };
}

function assertStrictBackup(path: string, expected: Snapshot) {
  const validation = spawnSync(process.execPath, [
    join(findJavaProject(), "recovery/library-recovery.mjs"), "validate", path,
  ], { encoding: "utf8", timeout: 10000 });
  assert.equal(validation.status, 0, validation.stderr);
  // Normalize SQLite's null-prototype row objects, not the actual values.
  assert.deepEqual(JSON.parse(JSON.stringify(readSqliteSnapshot(path))), expected);
}

test("SQL adaptation preserves bound parameters and camel-case response fields", () => {
  assert.equal(postgresSql("SELECT user_id AS userId FROM users WHERE ? IS NULL ORDER BY username COLLATE NOCASE"),
    'SELECT user_id AS "userId" FROM users WHERE $1::text IS NULL ORDER BY lower(username)');
});

test("durable browser records survive new processes and SQLite backup/restore stays compatible", async () => {
  const admin = new pg.Pool({ connectionString: process.env.DATABASE_URL });
  const schema = `library_fixture_${Date.now()}_${process.pid}`;
  const options = `-c search_path=${schema}`;
  const project = findJavaProject();
  const directory = mkdtempSync(join(tmpdir(), "library-redeploy-fixture-"));
  let pool: pg.Pool | undefined;
  let server: ReturnType<ReturnType<typeof express>["listen"]> | undefined;
  try {
    await admin.query(`CREATE SCHEMA ${schema}`);
    pool = new pg.Pool({ connectionString: process.env.DATABASE_URL, options });
    // Disposable, real PostgreSQL schema based on the approved SQLite constraints.
    // Never alter the application's public schema or seed real records in this test.
    await pool.query(fixtureDdl());
    const store = new PostgresLibraryStore(pool);
    await store.assertReady();
    await store.importSnapshot(fixture);
    await assert.rejects(store.importSnapshot(fixture), /not empty/);

    const app = express();
    app.use(express.json());
    app.use((req, _res, next) => {
      Object.assign(req, { log: { error() {} } });
      next();
    });
    app.use("/api/library", createLibraryRouter(store, async () => ({
      signedIn: true, canManage: true,
    })));
    server = app.listen(0, "127.0.0.1");
    await new Promise<void>((resolve) => server!.once("listening", resolve));
    const address = server.address() as { port: number };
    const call = async (path: string, method = "GET", body?: unknown) => {
      const response = await fetch(`http://127.0.0.1:${address.port}/api/library${path}`, {
        method, headers: { "Content-Type": "application/json", "Sec-Fetch-Site": "same-origin" },
        ...(body === undefined ? {} : { body: JSON.stringify(body) }),
      });
      return { status: response.status, data: response.status === 204 ? null : await response.json() as any };
    };
    assert.equal((await call("/games?search=%25&genreId=7")).data[0].genreId, 7);
    assert.deepEqual((await call("/summary")).data, {
      games: 1, players: 1, savedGames: 1, totalPlays: 2, genres: 1,
    });
    const updated = await call("/saved/11/17", "PUT", { rating: 5, playCount: 21 });
    assert.equal(updated.status, 200);
    assert.equal(updated.data.playCount, 21);
    assert.equal(updated.data.userId, 11);
    assert.equal((await call("/saved", "POST", { userId: 11, gameId: 17, rating: null, playCount: 0 })).status, 409);
    const created = await call("/players", "POST", { username: "Another Fixture", email: "another@example.test" });
    assert.equal(created.status, 201);
    assert.ok(created.data.id > 11, "imported IDs advance generated identities");
    const gameBody = { title: "Second Fixture", genreId: 7, url: "https://example.test/second", releaseDate: "2020-02-02" };
    const newGame = await call("/games", "POST", gameBody);
    assert.equal(newGame.status, 201);
    assert.ok(newGame.data.id > 17);
    assert.equal((await call("/games", "POST", gameBody)).status, 409);
    assert.equal((await call(`/games/${newGame.data.id}`, "PUT", { ...gameBody, title: "Changed Fixture" })).data.title, "Changed Fixture");
    assert.equal((await call(`/players/${created.data.id}`, "PUT", {
      username: "Changed Player", email: "changed@example.test",
    })).data.username, "Changed Player");
    const link = { userId: created.data.id, gameId: newGame.data.id, rating: null, playCount: 3 };
    assert.equal((await call("/saved", "POST", link)).status, 201);
    assert.equal((await call(`/saved/${link.userId}/${link.gameId}`, "DELETE")).status, 204);
    assert.equal((await call(`/saved/${link.userId}/${link.gameId}`, "DELETE")).status, 404);
    assert.equal((await call("/saved", "POST", link)).status, 201);
    assert.equal((await call(`/games/${newGame.data.id}`, "DELETE")).status, 204);
    assert.equal((await call("/saved")).data.length, 1, "game deletion cascades only its saved link");
    assert.equal((await call(`/players/${created.data.id}`, "DELETE")).status, 204);
    assert.equal((await call("/games", "POST", { ...gameBody, genreId: 99999 })).status, 400);
    const statistics = (await call("/statistics")).data.find((row: { userId: number }) => row.userId === 11);
    assert.equal(statistics.totalPlayCount, 21);
    assert.equal(statistics.averageRating, 5);

    // Simulate a deployment process being discarded, including every local file.
    await new Promise<void>((resolve, reject) => server!.close((error) => error ? reject(error) : resolve()));
    server = undefined;
    await pool.end();
    pool = undefined;
    const pgEntry = createRequire(join(process.cwd(), "package.json")).resolve("pg");
    const child = spawnSync(process.execPath, ["-e", `
      const { Pool } = require(${JSON.stringify(pgEntry)});
      const pool = new Pool({ connectionString: process.env.DATABASE_URL, options: ${JSON.stringify(options)} });
      (async () => {
        const rows = (await pool.query("SELECT rating, play_count FROM user_games WHERE user_id=11 AND game_id=17")).rows;
        if (rows[0]?.rating !== 5 || rows[0]?.play_count !== 21) process.exitCode = 1;
        await pool.end();
      })().catch(() => { process.exitCode = 1; });
    `], { cwd: directory, encoding: "utf8" });
    assert.equal(child.status, 0, child.stderr);
    pool = new pg.Pool({ connectionString: process.env.DATABASE_URL, options });
    const fresh = new PostgresLibraryStore(pool);
    const snapshot = await fresh.createBackup();
    try {
      const validation = spawnSync(process.execPath, [join(project, "recovery/library-recovery.mjs"), "validate", snapshot.path], { encoding: "utf8" });
      assert.equal(validation.status, 0, validation.stderr);
      const rows = readSqliteSnapshot(snapshot.path);
      assert.equal(rows.user_games[0].play_count, 21);
      // The snapshot opens directly with the independent Java app's SQLite model.
      const sqlite = new DatabaseSync(snapshot.path, { readOnly: true });
      assert.equal(sqlite.prepare("SELECT rating FROM user_games WHERE user_id=11 AND game_id=17").get()!.rating, 5);
      sqlite.close();
      const bad = structuredClone(rows);
      bad.user_games[0].game_id = 99999;
      await assert.rejects(fresh.importSnapshot(bad, true), /foreign key/i);
      await assert.rejects(fresh.importSnapshot(rows, true, async () => {
        throw new Error("Fixture archive could not be preserved");
      }), /could not be preserved/);
      assert.equal((await fresh.db.prepare("SELECT play_count FROM user_games WHERE user_id=? AND game_id=?").get(11, 17))!.play_count, 21,
        "failed recovery rolls back replacement atomically");
      let preservedCount: unknown;
      await fresh.importSnapshot(rows, true, async (before) => {
        preservedCount = before.user_games[0].play_count;
      });
      assert.equal(preservedCount, 21);
      assert.equal((await fresh.db.prepare("SELECT rating FROM user_games WHERE user_id=? AND game_id=?").get(11, 17))!.rating, 5);
    } finally { await snapshot.cleanup(); }

    // Successful materialization also supports explicit cleanup.
    const generated = await writeSqliteSnapshot(fixture);
    await generated.cleanup();
  } finally {
    if (server) await new Promise<void>((resolve) => server!.close(() => resolve()));
    await pool?.end();
    await admin.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);
    await admin.end();
    rmSync(directory, { recursive: true, force: true });
  }
});

test("PostgreSQL exports keep one snapshot across concurrent parent and saved-game changes", async (t) => {
  const scenarios = [
    {
      name: "parent key update cascades after genres were read",
      boundary: "FROM genres",
      sql: `UPDATE genres SET genre_id=8, genre_name='Changed Genre' WHERE genre_id=7;
        UPDATE user_games SET rating=5, play_count=91 WHERE user_id=11 AND game_id=17`,
      expected: (() => {
        const rows = structuredClone(fixture);
        rows.genres[0] = { genre_id: 8, genre_name: "Changed Genre" };
        rows.games[0].genre_id = 8;
        rows.user_games[0] = { user_id: 11, game_id: 17, rating: 5, play_count: 91 };
        return rows;
      })(),
    },
    {
      name: "game and saved-game edits commit after games were read",
      boundary: "FROM games",
      sql: `UPDATE games SET title='Changed Game' WHERE game_id=17;
        UPDATE users SET username='Changed Player' WHERE user_id=11;
        UPDATE user_games SET rating=4, play_count=42 WHERE user_id=11 AND game_id=17`,
      expected: (() => {
        const rows = structuredClone(fixture);
        rows.games[0].title = "Changed Game";
        rows.users[0].username = "Changed Player";
        rows.user_games[0] = { user_id: 11, game_id: 17, rating: 4, play_count: 42 };
        return rows;
      })(),
    },
    {
      name: "player deletion cascades after users were read",
      boundary: "FROM users",
      sql: "DELETE FROM users WHERE user_id=11",
      expected: { ...structuredClone(fixture), users: [], user_games: [] },
    },
  ];
  for (const scenario of scenarios) {
    await t.test(scenario.name, async () => withDisposableStore(async (pool, store) => {
      const writer = await pool.connect();
      let committed = false;
      const observed = observeExport(pool, async (sql) => {
        if (!sql.endsWith(scenario.boundary)) return;
        assert.equal(committed, false, "boundary must be reached exactly once");
        // The reader is still checked out, so this is a genuinely different
        // connection. COMMIT must complete before any subsequent export read.
        await writer.query("BEGIN");
        await writer.query(scenario.sql);
        await writer.query("COMMIT");
        committed = true;
      });
      let before: Awaited<ReturnType<PostgresLibraryStore["createBackup"]>> | undefined;
      let after: typeof before;
      try {
        before = await observed.store.createBackup();
        assert.equal(committed, true, "writer committed between export table reads");
        assert.equal(observed.releases(), 1);
        assert.equal(observed.statements.at(-1), "COMMIT");
        assertStrictBackup(before.path, fixture);

        // A fresh export must see the entire committed state. This also proves
        // that passing the old-snapshot assertion wasn't a no-op writer.
        after = await store.createBackup();
        assertStrictBackup(after.path, scenario.expected);
      } finally {
        await before?.cleanup();
        await after?.cleanup();
        writer.release();
      }
      assert.equal(existsSync(before!.path), false);
      assert.equal(existsSync(after!.path), false);
    }));
  }
});

test("failed PostgreSQL exports roll back and remove partial SQLite output", async (t) => {
  await withDisposableStore(async (pool, store) => {
    const directories: string[] = [];
    const mkdtemp = fsPromises.mkdtemp;
    t.mock.method(fsPromises, "mkdtemp", async (prefix: string) => {
      const directory = await mkdtemp(prefix);
      if (prefix.endsWith("browser-library-backup-")) directories.push(directory);
      return directory;
    });
    try {
      const failedRead = observeExport(pool, async (sql) => {
        if (sql.endsWith("FROM games")) throw new Error("Synthetic export read failure");
      });
      await assert.rejects(failedRead.store.createBackup(), /Synthetic export read failure/);
      assert.equal(failedRead.statements.at(-1), "ROLLBACK");
      assert.equal(failedRead.releases(), 1);
      assert.deepEqual(directories, [], "a failed read creates no SQLite output");

      // Relax only this disposable schema so invalid synthetic data reaches
      // SQLite and fails after a real temp DB and parent rows already exist.
      await pool.query("ALTER TABLE user_games DROP CONSTRAINT user_games_rating_check");
      await pool.query("UPDATE user_games SET rating=0");
      const failedWrite = observeExport(pool, async () => {});
      await assert.rejects(failedWrite.store.createBackup(), /CHECK constraint failed/i);
      assert.equal(failedWrite.statements.at(-1), "COMMIT");
      assert.equal(failedWrite.releases(), 1);
      assert.equal(directories.length, 1, "failure exercised real SQLite materialization");
      assert.equal(existsSync(directories[0]), false, "partial database and directory are removed");

      // A subsequent export still works after either failure, and successful
      // output is cleaned by its caller rather than discarded prematurely.
      await pool.query("UPDATE user_games SET rating=NULL");
      const recovered = await store.createBackup();
      try {
        assert.equal(directories.length, 2);
        assert.equal(existsSync(recovered.path), true);
        assertStrictBackup(recovered.path, fixture);
      } finally { await recovered.cleanup(); }
      assert(directories.every((directory) => !existsSync(directory)));
    } finally {
      t.mock.restoreAll();
      for (const directory of directories) rmSync(directory, { recursive: true, force: true });
    }
  });
});
